#!/usr/bin/env python3
"""Configure a Meson build directory with a compiler cache.

Meson cannot set a compiler launcher from ``meson.build``, so this wrapper
writes a native file that prefixes both compilers with ccache/sccache and then
runs ``meson setup``.  The detection order mirrors CMakeLists.txt
(``USE_CHACHE``): sccache first, ccache second, and ccache is never used for
MSVC-style compilers.

The native file is written next to the build directory (``<builddir>.native.ini``)
so the build directory itself stays empty for ``meson setup``.

Examples:
    python scripts/meson_setup.py builddir
    python scripts/meson_setup.py builddir --cache ccache
    python scripts/meson_setup.py builddir --compiler-c clang --compiler-cpp clang++
    python scripts/meson_setup.py builddir --no-cache -- --buildtype=debug

Exit codes:
    0  setup succeeded (with or without a cache)
    1  meson setup failed
    2  invalid arguments or meson was not found
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Sequence

CACHE_KINDS = ("auto", "sccache", "ccache", "none")
MSVC_STEMS = {"cl", "clang-cl"}
DEFAULT_C_COMPILER = "gcc"
DEFAULT_CXX_COMPILER = "g++"


@dataclass(frozen=True)
class CacheSelection:
    """The compiler-cache tool to wrap the compilers with."""

    tool: str | None
    reason: str


def _stem(value: str) -> str:
    """Return the lower-case executable name without a Windows extension."""
    name = Path(value.replace("\\", "/")).name.lower()
    return name.removesuffix(".exe")


def _find_tool(name: str) -> str | None:
    """Return the absolute path of a cache tool, or ``None``."""
    return shutil.which(name)


def _explicit_cache(kind: str, compiler_cpp: str) -> CacheSelection:
    """Return the selection for an explicitly requested cache."""
    if kind == "none":
        return CacheSelection(None, "disabled with --no-cache")
    tool = _find_tool(kind)
    if tool is None:
        return CacheSelection(None, f"{kind} was requested but is not on PATH")
    if kind == "ccache" and _stem(compiler_cpp) in MSVC_STEMS:
        return CacheSelection(None, "ccache does not support MSVC-style compilers")
    return CacheSelection(tool, kind)


def _auto_cache(compiler_cpp: str) -> CacheSelection:
    """Return the best available cache, mirroring CMake's order."""
    tool = _find_tool("sccache")
    if tool is not None:
        return CacheSelection(tool, "sccache (preferred)")
    tool = _find_tool("ccache")
    if tool is not None and _stem(compiler_cpp) not in MSVC_STEMS:
        return CacheSelection(tool, "ccache (sccache not found)")
    return CacheSelection(None, "no usable compiler cache was found")


def select_cache(kind: str, compiler_cpp: str) -> CacheSelection:
    """Pick the compiler cache, mirroring CMake's USE_CHACHE order."""
    if kind == "auto":
        return _auto_cache(compiler_cpp)
    return _explicit_cache(kind, compiler_cpp)


def _quote(value: str) -> str:
    """Render one native-file array element (Meson requires single quotes)."""
    escaped = value.replace("\\", "/").replace("'", "\\'")
    return f"'{escaped}'"


def native_file_path(builddir: Path) -> Path:
    """Return the native-file path next to the build directory."""
    name = builddir.name or "meson"
    return builddir.with_name(f"{name}.native.ini")


def write_native_file(path: Path, tool: str, compiler_c: str, compiler_cpp: str) -> None:
    """Write a native file that wraps both compilers with the cache tool."""
    path.parent.mkdir(parents=True, exist_ok=True)
    content = (
        "# Generated by scripts/meson_setup.py\n"
        "[binaries]\n"
        f"c = [{_quote(tool)}, {_quote(compiler_c)}]\n"
        f"cpp = [{_quote(tool)}, {_quote(compiler_cpp)}]\n"
    )
    path.write_text(content, encoding="utf-8")


def build_parser() -> argparse.ArgumentParser:
    """Build the command-line parser."""
    parser = argparse.ArgumentParser(
        description="Configure a Meson build directory with ccache/sccache.",
        epilog="Arguments after '--' are passed to 'meson setup'.",
    )
    parser.add_argument("builddir", type=Path, help="build directory to create")
    parser.add_argument(
        "--cache",
        choices=CACHE_KINDS,
        default="auto",
        help="compiler cache to use (default: auto = sccache, then ccache)",
    )
    parser.add_argument(
        "--compiler-c",
        default=os.environ.get("CC", DEFAULT_C_COMPILER),
        help=f"C compiler (default: $CC or {DEFAULT_C_COMPILER})",
    )
    parser.add_argument(
        "--compiler-cpp",
        default=os.environ.get("CXX", DEFAULT_CXX_COMPILER),
        help=f"C++ compiler (default: $CXX or {DEFAULT_CXX_COMPILER})",
    )
    parser.add_argument(
        "--no-cache",
        action="store_true",
        help="alias for --cache none",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Run the wrapper and return the process exit code."""
    args, extra = build_parser().parse_known_args(argv)
    if extra and extra[0] == "--":
        extra = extra[1:]
    meson = shutil.which("meson")
    if meson is None:
        print("error: meson was not found on PATH", file=sys.stderr)
        return 2
    kind = "none" if args.no_cache else args.cache
    selection = select_cache(kind, args.compiler_cpp)
    command = [meson, "setup", str(args.builddir)]
    if selection.tool is None:
        print(f"compiler cache: not used ({selection.reason})")
    else:
        native = native_file_path(args.builddir)
        write_native_file(native, selection.tool, args.compiler_c, args.compiler_cpp)
        command.extend(["--native-file", str(native)])
        print(f"compiler cache: {selection.reason} -> {native}")
    command.extend(extra)
    return subprocess.run(command, check=False).returncode


if __name__ == "__main__":
    sys.exit(main())
